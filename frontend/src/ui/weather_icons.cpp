const lv_img_dsc_t* get_weather_icon_dsc(const char* icon_code) {
    if (!icon_code || icon_code[0] == '\0') {
        return &img_weather_cloud;
    }

    char lower[32] = {0};
    int len = strlen(icon_code);
    if (len > 31) len = 31;
    for (int i = 0; i < len; i++) {
        lower[i] = tolower((unsigned char)icon_code[i]);
    }

    if (strstr(lower, "sun") || strstr(lower, "clear") || strstr(lower, "fair")) {
        return &img_weather_sun;
    }
    if (strstr(lower, "p_cloud") || strstr(lower, "partly")) {
        return &img_weather_p_cloud;
    }
    if (strstr(lower, "storm") || strstr(lower, "thunder")) {
        return &img_weather_storm;
    }
    if (strstr(lower, "drizzle")) {
        return &img_weather_drizzle;
    }
    if (strstr(lower, "rain") || strstr(lower, "shower")) {
        return &img_weather_rain;
    }
    if (strstr(lower, "snow") || strstr(lower, "flurr")) {
        return &img_weather_snow;
    }
    if (strstr(lower, "fog") || strstr(lower, "mist") || strstr(lower, "haze")) {
        return &img_weather_fog;
    }
    if (strstr(lower, "cloud") || strstr(lower, "overcast")) {
        return &img_weather_cloud;
    }

    return &img_weather_cloud;
}
